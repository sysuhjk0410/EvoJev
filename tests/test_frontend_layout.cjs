const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const vm=require('node:vm');
const source=fs.readFileSync(path.join(__dirname,'../web/app.js'),'utf8');
const functions=['fitPosition','moduleBox','moveModule','saveLayout','resetLayout','restoreLayout','finishDrag','initializeDragging'];
const selected=source.split('\n').filter(line=>functions.some(name=>line.startsWith('function '+name+'('))).join('\n');
assert.equal(selected.split('\n').length,functions.length);
const memory=new Map();
const stage={clientWidth:360,clientHeight:300,querySelectorAll:()=>modules};
function element(name,x){
  const classes=new Set(),handlers={},capture=new Set();
  const el={dataset:{node:name},offsetLeft:x,offsetTop:0,offsetWidth:150,offsetHeight:120,parentElement:stage,style:{},classList:{add:x=>classes.add(x),remove:x=>classes.delete(x)}};
  const handle={closest:()=>el,addEventListener:(name,fn)=>handlers[name]=fn,focus:()=>{},setPointerCapture:id=>capture.add(id),hasPointerCapture:id=>capture.has(id),releasePointerCapture:id=>capture.delete(id)};
  return {el,handle,handlers,classes,capture};
}
const a=element('harness',0),b=element('search',180),modules=[a.el,b.el],reset={};
const context={document:{querySelectorAll:selector=>selector==='.drag-handle'?[a.handle,b.handle]:modules},localStorage:{setItem:(k,v)=>memory.set(k,v),getItem:k=>memory.get(k)||null,removeItem:k=>memory.delete(k)},performance:{now:()=>0},drawMethod:()=>{},$:(id)=>id==='layout-reset'?{addEventListener:(name,fn)=>reset[name]=fn}:{classList:{contains:()=>true}}};
vm.createContext(context);
vm.runInContext("let dragState=null;const layoutKey='evojev-module-layout';"+selected,context);
const fit=context.fitPosition;
const limits=fit({w:150,h:120},{x:1000,y:1000},[],{w:360,h:300},{x:0,y:0});
assert.equal(limits.x,210);assert.equal(limits.y,180);
const blocked=fit({w:150,h:120},{x:180,y:0},[{x:180,y:0,w:150,h:120}],{w:360,h:300},{x:0,y:0});
assert.equal(blocked.x,0);assert.equal(blocked.y,0);
context.initializeDragging();
let prevented=0;
const event=(x,y)=>({button:0,pointerId:11,clientX:x,clientY:y,preventDefault:()=>prevented++});
a.handlers.pointerdown(event(100,100));
a.handlers.pointermove(event(120,160));
assert.equal(a.el.dataset.dx,'20');assert.equal(a.el.dataset.dy,'60');assert.ok(a.classes.has('dragging'));
a.handlers.pointerup(event(120,160));
assert.equal(a.capture.size,0);assert.ok(!a.classes.has('dragging'));assert.ok(memory.has('evojev-module-layout'));
a.handlers.keydown({key:'ArrowDown',shiftKey:false,preventDefault:()=>prevented++});
assert.equal(a.el.dataset.dy,'76');
a.handlers.pointerdown(event(120,160));a.handlers.pointermove(event(120,210));a.handlers.pointercancel(event(120,210));
assert.equal(a.el.dataset.dy,'76');assert.equal(a.capture.size,0);
context.resetLayout(false);assert.equal(a.el.dataset.dy,'0');
context.restoreLayout();assert.equal(Number(a.el.dataset.dy),76);
reset.click();assert.equal(a.el.dataset.dx,'0');assert.equal(a.el.dataset.dy,'0');assert.equal(memory.size,0);
a.handlers.pointerdown({...event(100,100),button:2});assert.equal(a.capture.size,0);
assert.ok(prevented>=3);
console.log('Frontend layout: bounds, collisions, pointer movement, cancellation, keyboard, persistence and reset passed.');
